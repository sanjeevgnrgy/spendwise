"""Write the backend's contract for the web app, so the two can't drift apart.

- web/openapi.json: the REST API (FastAPI's OpenAPI document). `npm run gen:api` turns it into
  TypeScript types (web/src/shared/api/schema.gen.ts).
- web/src/shared/api/contracts.gen.ts: the names and limits that aren't in OpenAPI (A2UI catalogs and
  actions, AG-UI event names and keys, payment-method labels, limits).

Run from the project folder after changing an API or one of these values, then `cd web; npm run gen:api`:
    .\\.venv\\Scripts\\python.exe backend\\scripts\\export_contracts.py
"""

import json
import sys
from pathlib import Path
from typing import get_args

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from app.core.config import API_PREFIX, PROJECT_DIR  # noqa: E402
from app.core.errors import PROBLEM_JSON  # noqa: E402
from app.core.money import CURRENCY_SYMBOLS, DEFAULT_CURRENCY  # noqa: E402
from app.main import app  # noqa: E402
from app.modules.assistant.a2ui import MAX_USER_MESSAGE_LENGTH, ActionName, Catalog  # noqa: E402
from app.modules.assistant.a2ui.models import (  # noqa: E402
    A2UI_VERSION,
    MAX_CHART_POINTS,
    MAX_UNIT_LENGTH,
    ROOT_ID,
    ChartType,
    Component,
    Trend,
)
from app.modules.assistant.protocol import FORWARDED_A2UI_ACTION, STATE_DATA_VERSION, CustomEventName, MetadataKey  # noqa: E402
from app.modules.assistant.schemas import MAX_MESSAGE_LENGTH  # noqa: E402
from app.modules.categories import UNKNOWN_CATEGORY  # noqa: E402
from app.modules.conversations import THREAD_ID_MAX_LENGTH  # noqa: E402
from app.modules.expenses import PAYMENT_METHOD_LABELS  # noqa: E402
from app.modules.expenses.contracts import (  # noqa: E402
    DEFAULT_LIST_LIMIT,
    DEFAULT_TREND_MONTHS,
    MAX_LIST_LIMIT,
    MAX_TREND_MONTHS,
)

WEB_DIR = PROJECT_DIR / "web"
HEADER = (
    "// GENERATED by backend/scripts/export_contracts.py. Do not edit by hand:\n"
    "// change the value in the backend, then run the script again.\n\n"
)


def _const(name: str, value: object) -> str:
    # JSON is valid TypeScript, and `as const` keeps the exact values as types.
    return f"export const {name} = {json.dumps(value, indent=2, ensure_ascii=False)} as const\n"


def _component_names() -> dict[str, str]:
    """Every component type the server may send ({"Text": "Text", ...}), read from the models themselves."""
    union = get_args(Component)[0]
    return {model.model_fields["component"].default: model.model_fields["component"].default for model in get_args(union)}


def main() -> None:
    openapi = WEB_DIR / "openapi.json"
    openapi.write_text(json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    contracts = {
        "API_PREFIX": API_PREFIX,
        "PROBLEM_JSON": PROBLEM_JSON,
        "DEFAULT_CURRENCY": DEFAULT_CURRENCY,
        "CURRENCY_SYMBOLS": CURRENCY_SYMBOLS,
        "UNKNOWN_CATEGORY": UNKNOWN_CATEGORY,
        "PAYMENT_METHOD_LABELS": {method.value: label for method, label in PAYMENT_METHOD_LABELS.items()},
        "LIMITS": {
            "messageLength": MAX_MESSAGE_LENGTH,
            "threadIdLength": THREAD_ID_MAX_LENGTH,
            "userMessageLength": MAX_USER_MESSAGE_LENGTH,
            "listDefault": DEFAULT_LIST_LIMIT,
            "listMax": MAX_LIST_LIMIT,
            "trendMonthsDefault": DEFAULT_TREND_MONTHS,
            "trendMonthsMax": MAX_TREND_MONTHS,
        },
        "A2UI": {
            "version": A2UI_VERSION,
            "rootId": ROOT_ID,
            "catalogs": {"basic": Catalog.BASIC.value, "insights": Catalog.INSIGHTS.value},
            "components": _component_names(),
            "insights": {
                "chartTypes": {kind.name.lower(): kind.value for kind in ChartType},
                "trends": {trend.name.lower(): trend.value for trend in Trend},
                "maxChartPoints": MAX_CHART_POINTS,
                "maxUnitLength": MAX_UNIT_LENGTH,
            },
            "actions": {
                "saveExpense": ActionName.SAVE_EXPENSE.value,
                "approveDelete": ActionName.APPROVE_DELETE.value,
                "cancelDelete": ActionName.CANCEL_DELETE.value,
            },
        },
        "AGUI": {
            "customEvents": {"a2ui": CustomEventName.A2UI.value},
            "forwardedA2uiAction": FORWARDED_A2UI_ACTION,
            "stateDataVersion": STATE_DATA_VERSION,
            "metadata": {key.name.lower(): key.value for key in MetadataKey},
        },
    }
    target = WEB_DIR / "src" / "shared" / "api" / "contracts.gen.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HEADER + "\n".join(_const(name, value) for name, value in contracts.items()), encoding="utf-8")
    print(f"Wrote {openapi.relative_to(PROJECT_DIR)} and {target.relative_to(PROJECT_DIR)}")


if __name__ == "__main__":
    main()
